    public void getProducts() {
        ProductDAO p = new ProductDAO();
        
        List<Product> products = p.getAll();
        
        DefaultTableModel table = (DefaultTableModel) tblProduct.getModel();
        
        for (Product prod : products) {
            Object[] obj = new Object[] {
                prod.getId(),
                prod.getDescription(),
                prod.getBarcode(),
                prod.getSku(),
                prod.getValue(),
                prod.isActive(),
                prod.getNcm()
            };
            table.addRow(obj);
        }
    }

