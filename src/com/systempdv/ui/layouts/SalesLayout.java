    private void btnFinishActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFinishActionPerformed
        if (current.getItems().isEmpty()) {
            JOptionPane.showMessageDialog(this, "A venda está vazia!", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String client = JOptionPane.showInputDialog(this, "Digite CPF do cliente:");
        current.setClient(client);

        Object[] options = {"DINHEIRO", "CRÉDITO", "DÉBITO", "PIX"};
        int choice = JOptionPane.showOptionDialog(
                this,
                "Total a pagar: R$ " + current.getTotalAmount().toString().replace(".", ",") + "\nSelecione o método de pagamento:",
                "Finalizar Venda",
                JOptionPane.DEFAULT_OPTION,
                JOptionPane.QUESTION_MESSAGE,
                null, options, options[0]);

        if (choice >= 0) {
            if (choice == 0) {
                current.setPaymentMethod(PaymentMethod.CASH);
            } else if (choice == 1) {
                current.setPaymentMethod(PaymentMethod.CREDIT);
            } else if (choice == 2) {
                current.setPaymentMethod(PaymentMethod.DEBIT);
            } else if (choice == 3) {
                current.setPaymentMethod(PaymentMethod.PIX);
            }

            boolean success = sDAO.save(current);

            if (success) {
                JOptionPane.showMessageDialog(this, "Venda finalizada com sucesso!");
                startNewSale();
            } else {
                JOptionPane.showMessageDialog(this, "Erro ao gravar a venda no banco de dados.", "Erro Crítico", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnFinishActionPerformed

    private void txtProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtProductActionPerformed
        String sku = txtProduct.getText().trim();
        if (sku.isEmpty()) {
            return;
        }

        int qtd = 1;
        try {
            qtd = Integer.parseInt(txtQtd.getText().trim());
            if (qtd <= 0) {
                qtd = 1;
            }
        } catch (NumberFormatException e) {
            qtd = 1;
        }

        Optional<Product> product = service.findBySku(sku);

        if (product.isPresent()) {
            Product p = product.get();
            SaleItem item = new SaleItem(p.getSku(), qtd, p.getPrice());

            current.addItem(item);
            DefaultTableModel table = (DefaultTableModel) tblItemSales.getModel();
            table.addRow(new Object[]{
                p.getSku(),
                p.getName(),
                p.getPrice(),
                item.getSubtotal()
            });

            txtValue.setText(p.getPrice().toString().replace(".", ","));
            lblValue.setText(current.getTotalAmount().toString().replace(".", ","));

            txtProduct.setText("");
            txtQtd.setText("1");
            txtProduct.requestFocus();
        } else {
            JOptionPane.showMessageDialog(this, "Produto não encontrado!", "Erro", JOptionPane.ERROR_MESSAGE);
            txtProduct.selectAll();
        }
    }//GEN-LAST:event_txtProductActionPerformed

