    private void btnInsertActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInsertActionPerformed
        ProductFormDialog dialog = new ProductFormDialog((Frame) SwingUtilities.getWindowAncestor(this), true);

        dialog.setVisible(true);
        Product newProduct = dialog.getProduct();
        if (newProduct != null) {
            if (service.save(newProduct)) {
                loadTable();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Erro ao salvar. SKU pode já existir.");
            }
        }
    }//GEN-LAST:event_btnInsertActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        String sku = JOptionPane.showInputDialog(this, "Digite o SKU do produto para editar:");
        
        if (sku != null && !sku.trim().isEmpty()) {
            Optional<Product> productOpt = service.findBySku(sku);

            if (productOpt.isPresent()) {
                ProductFormDialog dialog = new ProductFormDialog((Frame)SwingUtilities.getWindowAncestor(this), true, productOpt.get());
                
                dialog.setVisible(true); 

                Product product = dialog.getProduct();
                
                if (product != null) {
                    if (service.update(product)) {
                        loadTable();
                    } else {
                        JOptionPane.showMessageDialog(this, "Erro ao atualizar produto.");
                    }
                }
            } else {
                JOptionPane.showMessageDialog(this, "Produto não encontrado com o SKU: " + sku, "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String sku = JOptionPane.showInputDialog(this, "Digite o SKU do produto para excluir:");

        if (sku != null && !sku.trim().isEmpty()) {
            Optional<Product> product = service.findBySku(sku);

            if (product.isPresent()) {
                Product p = product.get();

                int confirm = JOptionPane.showConfirmDialog(this,
                        "Deseja realmente excluir o produto?\n\nSKU: " + p.getSku() + "\nNome: " + p.getName(),
                        "Confirmar Exclusão",
                        javax.swing.JOptionPane.YES_NO_OPTION,
                        javax.swing.JOptionPane.WARNING_MESSAGE);

                if (confirm == javax.swing.JOptionPane.YES_OPTION) {
                    if (service.delete(p.getSku())) {
                        loadTable();
                    } else {
                        JOptionPane.showMessageDialog(this, "Erro ao excluir o produto.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
                    }
                }
            } else {
                JOptionPane.showMessageDialog(this, "Produto não encontrado.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void loadTable() {
        DefaultTableModel table = (DefaultTableModel) tblProducts.getModel();
        table.setRowCount(0);

        List<Product> products = service.findAll();

        for (Product p : products) {
            table.addRow(new Object[]{
                p.getSku(),
                p.getName(),
                p.getCategory(),
                p.getPrice(),
                p.getStock()
            });
        }

        table.fireTableDataChanged();

        tblProducts.repaint();
        tblProducts.revalidate();
    }

