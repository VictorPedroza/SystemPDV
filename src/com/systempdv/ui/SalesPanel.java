    private void btnOpenSaleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnOpenSaleActionPerformed
        int selected = tblSales.getSelectedRow();

        if (selected == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um item da tabela para cancelar o Item", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        Integer saleId = (Integer) tblSales.getValueAt(selected, 0);

        Optional<Sale> sale = service.findById(saleId);
        
        if (sale.isPresent()) {
            showSaleDetailsDialog(sale.get());
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao carregar detalhes da venda.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnOpenSaleActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int selected = tblSales.getSelectedRow();

        if (selected == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um item da tabela para cancelar o Item", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Optional<Sale> sale = service.findById(selected);

        if (sale.isPresent()) {
            Sale s = sale.get();

            int confirm = JOptionPane.showConfirmDialog(this,
                    "Deseja realmente excluir a venda?\n\nID: " + s.getId(),
                    "Confirmar Exclusão",
                    javax.swing.JOptionPane.YES_NO_OPTION,
                    javax.swing.JOptionPane.WARNING_MESSAGE);

            if (confirm == javax.swing.JOptionPane.YES_OPTION) {
                if (service.delete(s.getId())) {
                    loadTable();
                } else {
                    JOptionPane.showMessageDialog(this, "Erro ao excluir o produto.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
                }
            }
        } else {
            JOptionPane.showMessageDialog(this, "Produto não encontrado.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void loadTable() {
        DefaultTableModel table = (DefaultTableModel) tblSales.getModel();
        table.setRowCount(0);

        List<Sale> sales = service.findAll();

        for (Sale s : sales) {
            table.addRow(new Object[]{
                s.getId(),
                s.getUserId(),
                s.getClient(),
                s.getPaymentMethod(),
                s.getTotalAmount().toString().replace(".", ","),
                s.getCreatedAt().toString()
            });
        }

        table.fireTableDataChanged();

        tblSales.repaint();
        tblSales.revalidate();
    }

    private void showSaleDetailsDialog(Sale sale) {
        String[] columnNames = {"SKU", "Quantidade", "Preço Unit.", "Subtotal"};
        DefaultTableModel model = new javax.swing.table.DefaultTableModel(columnNames, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        // 2. Preenche os itens
        for (SaleItem item : sale.getItems()) {
            model.addRow(new Object[]{
                item.getProductSku(),
                item.getQtd(),
                "R$ " + item.getPrice().toString().replace(".", ","),
                "R$ " + item.getSubtotal().toString().replace(".", ",")
            });
        }

        JTable tblItems = new JTable(model);
        JScrollPane panel = new JScrollPane(tblItems);
        panel.setPreferredSize(new Dimension(500, 200));

        JPanel header = new JPanel(new java.awt.GridLayout(3, 1));
        DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm");

        header.add(new JLabel("Venda Nº: " + sale.getId() + "   |   Data: " + sale.getCreatedAt().format(formatter)));
        header.add(new JLabel("Pagamento: " + sale.getPaymentMethod().name()));

        JLabel lblTotal = new JLabel("Total: R$ " + sale.getTotalAmount().toString().replace(".", ","));
        lblTotal.setFont(new java.awt.Font("Arial", java.awt.Font.BOLD, 16));
        header.add(lblTotal);

        javax.swing.JPanel mainPanel = new javax.swing.JPanel(new java.awt.BorderLayout(0, 10));
        mainPanel.add(header, java.awt.BorderLayout.NORTH);
        mainPanel.add(panel, java.awt.BorderLayout.CENTER);

        JOptionPane.showMessageDialog(this, mainPanel, "Detalhes da Venda", javax.swing.JOptionPane.PLAIN_MESSAGE);
    }

