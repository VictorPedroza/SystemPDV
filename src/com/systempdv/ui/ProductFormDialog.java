    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        try {
            String sku = txtSku.getText().trim();
            String name = txtName.getText().trim();
            String category = txtCategory.getText().trim();
            BigDecimal price = new BigDecimal(txtPrice.getText().replace(",", "."));
            Integer stock = Integer.parseInt(txtStock.getText());

            this.product = new Product(sku, name, category, price, stock);
            this.dispose();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Preço inválido.", "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnCancelActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelActionPerformed
        this.product = null;
        this.dispose();
    }//GEN-LAST:event_btnCancelActionPerformed

