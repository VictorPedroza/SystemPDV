    /**
     * Creates new form Interface
     */
    public Interface(ApplicationContext context) {
        initComponents();
        
        this.context = context;
        
        // Estilização
        setTitle("System PDV");
        setSize(1200,800);
        setResizable(false);
        setLocationRelativeTo(null);
        
        // Inicializa Layouts
        content = new JPanel();
        manager = new LayoutManagerUI(content);
        
        adminLayout = new AdminLayout(context);
        
        Database database = new Database(context);
        ProductDAO pDAO = new ProductDAO(database);
        SaleDAO sDAO = new SaleDAO(database);
        ProductService service = new ProductService(pDAO);
        salesLayout = new SalesLayout(context, service, sDAO);
        
        manager.addLayout("ADMINISTRATIVO", adminLayout);
        manager.addLayout("CAIXA", salesLayout);
        
        getContentPane().removeAll();
        getContentPane().setLayout(new BorderLayout());
        getContentPane().add(content, BorderLayout.CENTER);
        
        manager.showLayout(context.getProperty("default.system"));
    }

